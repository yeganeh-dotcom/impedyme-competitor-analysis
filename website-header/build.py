README_TXT = """=== Impedyme Hero Slider ===
Requires at least: 5.8
Requires PHP: 7.4
Stable tag: 1.0.0
License: GPLv2 or later

Responsive two-slide homepage header for impedyme.com.

== Usage ==
Add the shortcode [impedyme_hero] to a full-width section (for example a BeBuilder
Column item in place of the old Slider Revolution shortcodes, an Elementor
"Shortcode" widget, or a Gutenberg "Shortcode" block).

The videos and images are bundled in the plugin's media/ folder.
Text, links and timing live in templates/impedyme-hero.html and assets/.
"""

FIXED_DATE = (2026, 11, 9, 0, 0, 0)  # constant timestamps keep the zip byte-identical between builds


def compact(code: str) -> str:
    """Drop blank lines so WordPress auto-paragraphs can never split inline CSS/JS."""
    return re.sub(r"\n\s*\n", "\n", code.replace("\r", ""))


def fill(markup: str, mapping: dict[str, str]) -> str:
    for token, value in mapping.items():
        markup = markup.replace(token, value)
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", markup)
    if leftover:
        raise SystemExit(f"unreplaced placeholders: {sorted(set(leftover))}")
    return markup


def zip_add(z: zipfile.ZipFile, name: str, data: bytes, compress: bool = True) -> None:
    info = zipfile.ZipInfo(name, FIXED_DATE)
    info.external_attr = 0o644 << 16
    info.compress_type = zipfile.ZIP_DEFLATED if compress else zipfile.ZIP_STORED
    z.writestr(info, data)


def main() -> None:
    css = (SRC / "impedyme-hero.css").read_text(encoding="utf-8")
    js = (SRC / "impedyme-hero.js").read_text(encoding="utf-8")
    markup = (SRC / "impedyme-hero.html").read_text(encoding="utf-8")
    for name in MEDIA_FILES.values():
        if not (MEDIA / name).is_file():
            raise SystemExit(f"missing media file: media/{name}")

    # 1) Local preview
    preview_hero = fill(markup, {
        **{token: "media/" + name for token, name in MEDIA_FILES.items()},
        "{{STYLE}}": "",
        "{{SCRIPT}}": '<script src="src/impedyme-hero.js"></script>',
    })
    (ROOT / "index.html").write_text(PREVIEW_PAGE.replace("{{HERO}}", preview_hero.rstrip("\n")), encoding="utf-8")

    # 2) Paste-in snippet
    WP.mkdir(exist_ok=True)
    # The instructions comment sits inside <section>: outside it, WordPress would wrap it in a <p>.
    snippet = fill(markup, {
        **SNIPPET_MEDIA,
        "{{STYLE}}": SNIPPET_HEADER + '<style id="impedyme-hero-css">\n' + compact(css).strip() + "\n</style>",
        "{{SCRIPT}}": '<script id="impedyme-hero-js">\n' + compact(js).strip() + "\n</script>",
    })
    (WP / "impedyme-hero-snippet.html").write_text(snippet, encoding="utf-8")

    # 3) WordPress plugin
    with zipfile.ZipFile(WP / "impedyme-hero.zip", "w") as z:
        zip_add(z, "impedyme-hero/impedyme-hero.php", (WP / "plugin" / "impedyme-hero.php").read_bytes())
        zip_add(z, "impedyme-hero/readme.txt", README_TXT.encode())
        zip_add(z, "impedyme-hero/templates/impedyme-hero.html", markup.encode())
        zip_add(z, "impedyme-hero/assets/impedyme-hero.css", css.encode())
        zip_add(z, "impedyme-hero/assets/impedyme-hero.js", js.encode())
        for name in MEDIA_FILES.values():
            zip_add(z, "impedyme-hero/media/" + name, (MEDIA / name).read_bytes(), compress=False)

    for path in (ROOT / "index.html", WP / "impedyme-hero-snippet.html", WP / "impedyme-hero.zip"):
        print(f"built {path.relative_to(ROOT)}  ({path.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
