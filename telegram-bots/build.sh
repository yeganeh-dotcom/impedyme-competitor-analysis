#!/usr/bin/env bash
# Builds one paste-ready file per destination into dist/.
# Edit the sources (shared/, user-bot/, admin-bot/, sheet-logger/, website/), then run:  bash telegram-bots/build.sh
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p dist

banner() {
  printf '/**\n * %s\n * Generated by build.sh from the files in shared/ and %s - edit those, then rebuild.\n' "$1" "$2"
  printf ' * HOW TO INSTALL: delete ALL old code files in this Apps Script project, paste this whole file,\n'
  printf ' * fill SHEET_ID / USER_BOT_TOKEN / ADMIN_BOT_TOKEN in CONFIG below, then\n'
  printf ' * Deploy > Manage deployments > Edit (pencil) > Version: New version > Deploy  (keeps the same URL).\n */\n\n'
}

{ banner "USER BOT = Config + Core + UserBot" "user-bot/"
  cat shared/Config.gs; echo; cat shared/Core.gs; echo; cat user-bot/UserBot.gs; } > dist/user-bot.gs

{ banner "ADMIN BOT = Config + Core + AdminBot + AdminViews" "admin-bot/"
  cat shared/Config.gs; echo; cat shared/Core.gs; echo; cat admin-bot/AdminBot.gs; echo; cat admin-bot/AdminViews.gs; } > dist/admin-bot.gs

cp sheet-logger/Logger.gs dist/google-sheet.gs
cp website/footer.html dist/footer.html
echo "Built dist/: $(ls dist | tr '\n' ' ')"
